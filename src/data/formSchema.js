export const flattenFormFields = (schema) =>
    Object.entries(schema.fields).flatMap(([groupLabel, fields]) =>
        fields.map((field) => ({
            ...field,
            groupLabel,
        })),
    )

export const findFormFieldById = (schema, fieldId) =>
    flattenFormFields(schema).find((field) => field.id === fieldId) ?? null

export const buildInitialListRow = (field) =>
    field.columns.reduce((result, column) => {
        result[column.id] = column.defaultValue ?? ''
        return result
    }, {})

export const buildInitialFormData = (schema) =>
    flattenFormFields(schema).reduce((result, field) => {
        if (field.fieldType === 'list') {
            result[field.id] = []
            return result
        }

        result[field.id] = field.defaultValue ?? ''
        return result
    }, {})
